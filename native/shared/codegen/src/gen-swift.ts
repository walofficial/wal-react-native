/**
 * Swift emitter. Consumes the language-neutral model (openapi-model.ts), the design tokens,
 * the route table and the locale files, and writes:
 *
 *   native/ios/WALCore/Sources/WALAPI/Generated/Models.swift      Codable DTOs
 *   native/ios/WALCore/Sources/WALAPI/Generated/Operations.swift  one APIOperation per endpoint
 *   native/ios/WALCore/Sources/WALCore/Generated/Tokens.swift     design tokens as pure data
 *   native/ios/WALCore/Sources/WALCore/Generated/Routes.swift     Route enum + descriptors
 *   native/ios/WALCore/Sources/WALCore/Generated/L10nKeys.swift   translation keys
 *   native/ios/WALCore/Sources/WALCore/Resources/Locales/*.json   copied locale bundles
 *
 * Everything emitted here is deterministic so `check:drift` can diff the output against git.
 * The Kotlin emitter (gen-kotlin.ts) mirrors this file one-to-one.
 */
