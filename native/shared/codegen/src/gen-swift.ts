function swiftType(t: TypeRef): string {
  switch (t.kind) {
    case 'string':
      return 'String';
    case 'number':
      return 'Double';
    case 'integer':
      return 'Int';
    case 'boolean':
      return 'Bool';
    case 'any':
      return 'JSONValue';
    case 'file':
      return 'MultipartFile';
    case 'array':
      return `[${swiftType(t.items)}]`;
    case 'map':
      return `[String: ${swiftType(t.values)}]`;
    case 'ref':
    case 'enum':
    case 'object':
      return typeName(t.name);
  }
}

/** Direct (non-collection) references between named types, used for recursion detection. */
function directRefs(t: TypeRef, types: Map<string, NamedType>): string[] {
  switch (t.kind) {
    case 'ref':
    case 'object': {
      const target = types.get(t.name);
      if (target?.kind === 'alias') return directRefs(target.type, types);
      return target?.kind === 'object' ? [t.name] : [];
    }
    default:
      return [];
  }
}

function findRecursiveProperties(types: Map<string, NamedType>): Set<string> {
  // Returns "Type.property" pairs that must be boxed to break value-type recursion.
  const boxed = new Set<string>();
  const graph = new Map<string, { prop: string; to: string }[]>();
  for (const t of types.values()) {
    if (t.kind !== 'object') continue;
    graph.set(
      t.name,
      t.properties.flatMap((p) => directRefs(p.type, types).map((to) => ({ prop: p.name, to }))),
    );
  }
  const visiting = new Set<string>();
  const done = new Set<string>();
  const dfs = (node: string) => {
    if (done.has(node)) return;
    visiting.add(node);
    for (const edge of graph.get(node) ?? []) {
      if (visiting.has(edge.to)) {
        boxed.add(`${node}.${edge.prop}`);
      } else if (!done.has(edge.to)) {
        dfs(edge.to);
      }
    }
    visiting.delete(node);
    done.add(node);
  };
  for (const name of graph.keys()) dfs(name);
  return boxed;
}

