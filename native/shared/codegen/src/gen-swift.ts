function emitParamStruct(structName: string, params: Parameter[], kind: 'path' | 'query' | 'header'): string {
  if (params.length === 0) return `        public typealias ${structName} = NoParameters\n`;
  const props = params.map((p) => {
    const type = swiftType(p.type);
    return `${docComment(p.description, '        ')}        public var ${ident(p.name)}: ${p.required ? type : `${type}?`}`;
  });
  const initParams = params.map((p) => `${ident(p.name)}: ${swiftType(p.type)}${p.required ? '' : '? = nil'}`);
  const assigns = params.map((p) => `            self.${ident(p.name)} = ${ident(p.name)}`);
  let conformance = 'Encodable, Hashable, Sendable';
  let extra = '';
  if (kind === 'path') {
    conformance += ', PathParameters';
    extra = `        public var pathValues: [String: String] {\n            [${params.map((p) => `${swiftString(p.wireName)}: ParameterValue.string(${ident(p.name)})`).join(', ')}]\n        }\n`;
  } else if (kind === 'query') {
    conformance += ', QueryParameters';
    extra = `        public var queryItems: [URLQueryItem] {\n            var items: [URLQueryItem] = []\n${params
      .map((p) => `            items.append(contentsOf: ParameterValue.queryItems(${swiftString(p.wireName)}, ${ident(p.name)}))`)
      .join('\n')}\n            return items\n        }\n`;
  } else {
    conformance += ', HeaderParameters';
    extra = `        public var headerValues: [String: String] {\n            var values: [String: String] = [:]\n${params
      .map((p) => `            ParameterValue.assign(&values, ${swiftString(p.wireName)}, ${ident(p.name)})`)
      .join('\n')}\n            return values\n        }\n`;
  }
  return `    public struct ${structName}: ${conformance} {
${props.join('\n')}

        public init(${initParams.join(', ')}) {
${assigns.join('\n')}
        }
${extra}${emitCodingKeys(params).replace(/\n {4}/g, '\n        ')}    }
`;
}

function emitOperation(op: OperationModel): string {
  const name = typeName(op.typeName);
  const bodyType = op.body ? swiftType(op.body.type) : 'NoBody';
  const bodyEncoding = !op.body ? '.none' : op.body.multipart ? '.multipart' : '.json';
  const responseType = op.response ? swiftType(op.response) : 'EmptyResponse';
  const hasPath = op.pathParams.length > 0;
  const hasQuery = op.queryParams.length > 0;
  const hasHeaders = op.headerParams.length > 0;

  const initParams: string[] = [];
  const initAssigns: string[] = [];
  if (hasPath) {
    initParams.push('path: Path');
    initAssigns.push('        self.path = path');
  } else initAssigns.push('        self.path = NoParameters()');
  if (hasQuery) {
    initParams.push(op.queryParams.every((p) => !p.required) ? 'query: Query = Query()' : 'query: Query');
    initAssigns.push('        self.query = query');
  } else initAssigns.push('        self.query = NoParameters()');
  if (hasHeaders) {
    initParams.push(op.headerParams.every((p) => !p.required) ? 'headers: Headers = Headers()' : 'headers: Headers');
    initAssigns.push('        self.headers = headers');
  } else initAssigns.push('        self.headers = NoParameters()');
  if (op.body) {
    initParams.push(op.body.required ? `body: ${bodyType}` : `body: ${bodyType}? = nil`);
    initAssigns.push('        self.body = body');
  } else initAssigns.push('        self.body = nil');

  return `${docComment(op.description, '    ')}    /// \`${op.method} ${op.pathTemplate}\` (tag: ${op.tag})
    public struct ${name}: APIOperation {
        public static let operationId = ${swiftString(op.operationId)}
        public static let method: HTTPMethod = .${op.method.toLowerCase()}
        public static let pathTemplate = ${swiftString(op.pathTemplate)}
        public static let bodyEncoding: BodyEncoding = ${bodyEncoding}
        public typealias Body = ${bodyType}
        public typealias Response = ${responseType}

${emitParamStruct('Path', op.pathParams, 'path')}${emitParamStruct('Query', op.queryParams, 'query')}${emitParamStruct('Headers', op.headerParams, 'header')}
        public var path: Path
        public var query: Query
        public var headers: Headers
        public var body: Body?

        public init(${initParams.join(', ')}) {
${initAssigns.join('\n')}
        }
    }
`;
}

function emitOperations(model: ApiModel): string {
  const ops = model.operations.map(emitOperation).join('\n');
  const ids = model.operations.map((o) => `        ${swiftString(o.operationId)},`).join('\n');
  return `${HEADER}
import Foundation

/// Namespace for every generated API operation. One struct per OpenAPI operation.
public enum Operations {
${ops}
    /// Every operationId, in stable order (used by walctl and drift tests).
    public static let allOperationIds: [String] = [
${ids}
    ]
}
`;
}

