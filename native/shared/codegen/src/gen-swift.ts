// ---------------------------------------------------------------------------
// Identifier helpers
// ---------------------------------------------------------------------------

const SWIFT_KEYWORDS = new Set([
  'associatedtype', 'class', 'deinit', 'enum', 'extension', 'fileprivate', 'func', 'import', 'init', 'inout',
  'internal', 'let', 'open', 'operator', 'private', 'precedencegroup', 'protocol', 'public', 'rethrows', 'static',
  'struct', 'subscript', 'typealias', 'var', 'break', 'case', 'catch', 'continue', 'default', 'defer', 'do',
  'else', 'fallthrough', 'for', 'guard', 'if', 'in', 'repeat', 'return', 'throw', 'switch', 'where', 'while',
  'Any', 'as', 'await', 'false', 'is', 'nil', 'self', 'Self', 'super', 'throws', 'true', 'try', 'some', 'any',
]);

/** Members that would clash with synthesized protocol requirements on a Codable/Hashable struct. */
const RESERVED_MEMBERS = new Set(['hashValue', 'Type', 'CodingKeys', 'description_']);

/** Foundation / stdlib names a DTO must not shadow. */
const TYPE_BLOCKLIST = new Set([
  'Error', 'Data', 'Date', 'URL', 'Result', 'Task', 'Notification', 'Set', 'Character', 'Bundle', 'Thread',
  'Operation', 'Timer', 'Stream', 'Process', 'Locale', 'Unit', 'Progress', 'Expression', 'Measurement', 'Decimal',
  'Optional', 'Array', 'Dictionary', 'String', 'Int', 'Double', 'Bool', 'Float', 'Never', 'Void', 'Encoder', 'Decoder',
  'Operations', 'JSONValue', 'MultipartFile', 'EmptyResponse', 'NoBody', 'NoParameters', 'HTTPMethod', 'BodyEncoding',
]);

function ident(name: string): string {
  if (SWIFT_KEYWORDS.has(name)) return `\`${name}\``;
  if (RESERVED_MEMBERS.has(name)) return `${name}Value`;
  return name;
}

function typeName(name: string): string {
  const p = pascal(name);
  return TYPE_BLOCKLIST.has(p) ? `${p}Model` : p;
}

function enumCaseName(value: string): string {
  if (value === '') return 'empty';
  let c = camel(value);
  if (/^[0-9]/.test(value)) c = `_${camel(value)}`.replace(/^__/, '_');
  return ident(c);
}

function swiftString(s: string): string {
  return JSON.stringify(s);
}

function docComment(text: string | undefined, indent: string): string {
  if (!text) return '';
  return text
    .split('\n')
    .filter((l) => l.trim().length > 0)
    .map((l) => `${indent}/// ${l.trim()}`)
    .join('\n') + '\n';
}

