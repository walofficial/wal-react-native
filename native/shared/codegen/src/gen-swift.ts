export interface GeneratedFile { path: string; contents: string }

export function generateSwift(): GeneratedFile[] {
  const builder = new ModelBuilder(OPENAPI_JSON);
  const model = builder.build();
  const tokens = JSON.parse(fs.readFileSync(TOKENS_JSON, 'utf8'));
  const routes: RoutesJson = JSON.parse(fs.readFileSync(ROUTES_JSON, 'utf8'));
  const l10n = emitL10nKeys(RN_LOCALES_DIR);

  return [
    { path: path.join(SWIFT_API_GENERATED_DIR, 'Models.swift'), contents: emitModels(model, builder.types) },
    { path: path.join(SWIFT_API_GENERATED_DIR, 'Operations.swift'), contents: emitOperations(model) },
    { path: path.join(SWIFT_CORE_GENERATED_DIR, 'Tokens.swift'), contents: emitTokens(tokens) },
    { path: path.join(SWIFT_CORE_GENERATED_DIR, 'Routes.swift'), contents: emitRoutes(routes) },
    { path: path.join(SWIFT_CORE_GENERATED_DIR, 'L10nKeys.swift'), contents: l10n.swift },
  ];
}

export function writeGenerated(files: GeneratedFile[]): void {
  for (const f of files) {
    fs.mkdirSync(path.dirname(f.path), { recursive: true });
    fs.writeFileSync(f.path, f.contents);
  }
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const files = generateSwift();
  writeGenerated(files);
  copyLocales(RN_LOCALES_DIR, SWIFT_CORE_RESOURCES_LOCALES_DIR);
  for (const f of files) console.log(`wrote ${path.relative(process.cwd(), f.path)} (${f.contents.split('\n').length} lines)`);
  console.log(`copied locales to ${path.relative(process.cwd(), SWIFT_CORE_RESOURCES_LOCALES_DIR)}`);
}
