function flattenLocale(obj: Record<string, any>, prefix = ''): [string, string][] {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' ? flattenLocale(v, `${prefix}${k}.`) : [[`${prefix}${k}`, String(v)] as [string, string]],
  );
}

function emitL10nKeys(localesDir: string): { swift: string; locales: string[] } {
  const files = fs.readdirSync(localesDir).filter((f) => f.endsWith('.json')).sort();
  const locales = files.map((f) => path.basename(f, '.json'));
  const en = JSON.parse(fs.readFileSync(path.join(localesDir, 'en.json'), 'utf8'));
  const keys = flattenLocale(en).map(([k]) => k).sort();
  const seen = new Set<string>();
  const cases = keys.map((k) => {
    let c = ident(camel(k.replace(/\./g, '_')));
    while (seen.has(c)) c = `${c}_`;
    seen.add(c);
    return `    case ${c} = ${swiftString(k)}`;
  });
  const swift = `${HEADER}
import Foundation

/// Every translation key present in locales/en.json (the fallback locale). Other locales may omit keys.
public enum L10nKey: String, CaseIterable, Hashable, Sendable {
${cases.join('\n')}
}

public enum L10nCatalog {
    /// Supported locale codes, mirrors lib/i18n.ts supportedLocales (sorted).
    public static let supportedLocales: [String] = [${locales.map(swiftString).join(', ')}]
    public static let defaultLocale = "en"
}
`;
  return { swift, locales };
}

function copyLocales(localesDir: string, destDir: string): void {
  fs.mkdirSync(destDir, { recursive: true });
  for (const f of fs.readdirSync(localesDir).filter((f) => f.endsWith('.json'))) {
    const parsed = JSON.parse(fs.readFileSync(path.join(localesDir, f), 'utf8'));
    fs.writeFileSync(path.join(destDir, f), JSON.stringify(parsed, null, 2) + '\n');
  }
}

