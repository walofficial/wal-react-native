function emitProperty(owner: string, p: Property, boxed: Set<string>): string {
  const optional = p.optional || p.nullable;
  const base = swiftType(p.type);
  const type = optional ? `${base}?` : base;
  const wrapper = boxed.has(`${owner}.${p.name}`) ? '@Indirect ' : '';
  return `${docComment(p.description, '    ')}    ${wrapper}public var ${ident(p.name)}: ${type}`;
}

function emitCodingKeys(props: { wireName: string; name: string }[]): string {
  if (props.length === 0) return '';
  const lines = props.map((p) =>
    p.wireName === p.name ? `        case ${ident(p.name)}` : `        case ${ident(p.name)} = ${swiftString(p.wireName)}`,
  );
  return `\n    public enum CodingKeys: String, CodingKey {\n${lines.join('\n')}\n    }\n`;
}

function emitInit(owner: string, props: Property[], boxed: Set<string>): string {
  if (props.length === 0) return '    public init() {}\n';
  const params = props.map((p) => {
    const optional = p.optional || p.nullable;
    const type = swiftType(p.type);
    return `${ident(p.name)}: ${type}${optional ? '? = nil' : ''}`;
  });
  const assigns = props.map((p) => {
    const lhs = boxed.has(`${owner}.${p.name}`) ? `self.${ident(p.name)}` : `self.${ident(p.name)}`;
    const rhs = boxed.has(`${owner}.${p.name}`) ? ident(p.name) : ident(p.name);
    return `        ${lhs} = ${rhs}`;
  });
  return `    public init(\n        ${params.join(',\n        ')}\n    ) {\n${assigns.join('\n')}\n    }\n`;
}

function multipartTextExpr(t: TypeRef, value: string): string {
  switch (t.kind) {
    case 'string':
      return value;
    case 'integer':
    case 'number':
    case 'boolean':
      return `MultipartText.scalar(${value})`;
    case 'enum':
      return `${value}.rawValue`;
    default:
      return `MultipartText.json(${value})`;
  }
}

function emitMultipart(obj: ObjectType): string {
  const lines: string[] = [];
  for (const p of obj.properties) {
    const optional = p.optional || p.nullable;
    const name = ident(p.name);
    const wire = swiftString(p.wireName);
    const value = optional ? 'value' : name;
    const body = (() => {
      const t = p.type;
      if (t.kind === 'file') return `parts.append(.file(name: ${wire}, file: ${value}))`;
      if (t.kind === 'array' && t.items.kind === 'file') return `for file in ${value} { parts.append(.file(name: ${wire}, file: file)) }`;
      if (t.kind === 'array') return `for item in ${value} { parts.append(.text(name: ${wire}, value: ${multipartTextExpr(t.items, 'item')})) }`;
      return `parts.append(.text(name: ${wire}, value: ${multipartTextExpr(t, value)}))`;
    })();
    lines.push(optional ? `        if let value = ${name} { ${body} }` : `        ${body}`);
  }
  return `\nextension ${typeName(obj.name)}: MultipartEncodable {\n    public func multipartParts() -> [MultipartPart] {\n        var parts: [MultipartPart] = []\n${lines.join('\n')}\n        return parts\n    }\n}\n`;
}

function emitObject(obj: ObjectType, boxed: Set<string>): string {
  const name = typeName(obj.name);
  const props = obj.properties.map((p) => emitProperty(obj.name, p, boxed)).join('\n');
  let out = `${docComment(obj.description, '')}public struct ${name}: Codable, Hashable, Sendable {\n`;
  if (obj.properties.length > 0) out += `${props}\n\n`;
  out += emitInit(obj.name, obj.properties, boxed);
  out += emitCodingKeys(obj.properties);
  out += '}\n';
  if (obj.multipart) out += emitMultipart(obj);
  return out;
}

/**
 * Enums are emitted as extensible string wrappers so an unknown server value never fails decoding
 * (the RN app treats these as plain strings). Known values are exposed as static members.
 */
function emitEnum(name: string, values: string[], description?: string): string {
  const swiftName = typeName(name);
  const seen = new Set<string>();
  const cases = values.map((v) => {
    let c = enumCaseName(v);
    while (seen.has(c)) c = `${c}_`;
    seen.add(c);
    return `    public static let ${c} = ${swiftName}(rawValue: ${swiftString(v)})`;
  });
  const known = [...seen].map((c) => `.${c.replace(/`/g, '')}`).join(', ');
  return `${docComment(description, '')}public struct ${swiftName}: RawRepresentable, Codable, Hashable, Sendable, ExpressibleByStringLiteral, CustomStringConvertible {
    public let rawValue: String
    public init(rawValue: String) { self.rawValue = rawValue }
    public init(stringLiteral value: String) { self.rawValue = value }
    public init(from decoder: Decoder) throws { self.rawValue = try decoder.singleValueContainer().decode(String.self) }
    public func encode(to encoder: Encoder) throws { var c = encoder.singleValueContainer(); try c.encode(rawValue) }
    public var description: String { rawValue }
    public var isKnown: Bool { Self.known.contains(self) }
${cases.join('\n')}
    public static let known: [${swiftName}] = [${known}]
}
`;
}

function emitModels(model: ApiModel, types: Map<string, NamedType>): string {
  const boxed = findRecursiveProperties(types);
  const chunks: string[] = [HEADER, 'import Foundation\n'];
  for (const t of model.types) {
    switch (t.kind) {
      case 'object':
        chunks.push(emitObject(t, boxed));
        break;
      case 'enum':
        chunks.push(emitEnum(t.name, t.values, t.description));
        break;
      case 'alias':
        chunks.push(`${docComment(t.description, '')}public typealias ${typeName(t.name)} = ${swiftType(t.type)}\n`);
        break;
    }
  }
  return chunks.join('\n');
}

