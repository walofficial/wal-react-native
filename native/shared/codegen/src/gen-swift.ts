type JsonAny = string | number | boolean | null | JsonAny[] | { [k: string]: JsonAny };

const TOKEN_META_KEYS = new Set(['$schema', 'description', 'note']);

function isColorToken(v: JsonAny): v is { light: string; dark: string } {
  return !!v && typeof v === 'object' && !Array.isArray(v) && typeof v.light === 'string' && typeof v.dark === 'string';
}

function numberLiteral(n: number): { type: string; literal: string } {
  return Number.isInteger(n) ? { type: 'Int', literal: String(n) } : { type: 'Double', literal: String(n) };
}

function emitTokenNamespace(name: string, obj: { [k: string]: JsonAny }, indent: string): string {
  const pad = indent + '    ';
  const lines: string[] = [];
  const description = typeof obj.description === 'string' ? obj.description : undefined;
  lines.push(`${docComment(description, indent)}${indent}public enum ${pascal(name)} {`);
  const colorEntries: string[] = [];
  for (const [key, value] of Object.entries(obj)) {
    if (TOKEN_META_KEYS.has(key)) continue;
    const member = ident(camel(key));
    if (isColorToken(value)) {
      lines.push(`${pad}public static let ${member} = ColorToken(light: ${swiftString(value.light)}, dark: ${swiftString(value.dark)})`);
      colorEntries.push(`${swiftString(key)}: ${member}`);
    } else if (typeof value === 'string') {
      lines.push(`${pad}public static let ${member}: String = ${swiftString(value)}`);
    } else if (typeof value === 'number') {
      const { type, literal } = numberLiteral(value);
      lines.push(`${pad}public static let ${member}: ${type} = ${literal}`);
    } else if (typeof value === 'boolean') {
      lines.push(`${pad}public static let ${member}: Bool = ${value}`);
    } else if (Array.isArray(value)) {
      if (value.every((v) => typeof v === 'number')) {
        lines.push(`${pad}public static let ${member}: [Double] = [${(value as number[]).map(String).join(', ')}]`);
      } else if (value.every((v) => typeof v === 'string')) {
        lines.push(`${pad}public static let ${member}: [String] = [${(value as string[]).map(swiftString).join(', ')}]`);
      } else {
        throw new Error(`Unsupported token array at ${name}.${key}`);
      }
    } else if (value && typeof value === 'object') {
      lines.push(emitTokenNamespace(key, value, pad));
    }
  }
  if (colorEntries.length > 0) {
    lines.push(`${pad}public static let all: [String: ColorToken] = [\n${colorEntries.map((e) => `${pad}    ${e},`).join('\n')}\n${pad}]`);
  }
  lines.push(`${indent}}`);
  return lines.join('\n');
}

function emitTokens(tokens: { [k: string]: JsonAny }): string {
  const body = Object.entries(tokens)
    .filter(([k, v]) => !TOKEN_META_KEYS.has(k) && v && typeof v === 'object' && !Array.isArray(v))
    .map(([k, v]) => emitTokenNamespace(k, v as { [k: string]: JsonAny }, '    '))
    .join('\n\n');
  return `${HEADER}
import Foundation

/// A colour pair resolved per colour scheme. Values are CSS strings (#rrggbb, #rrggbbaa or rgba(r,g,b,a)).
public struct ColorToken: Hashable, Sendable {
    public let light: String
    public let dark: String
    public init(light: String, dark: String) {
        self.light = light
        self.dark = dark
    }
    public func resolved(dark isDark: Bool) -> String { isDark ? dark : light }
}

/// Design tokens mirrored from native/shared/design/tokens.json. Pure data; no UIKit/SwiftUI.
public enum Tokens {
${body}
}
`;
}

